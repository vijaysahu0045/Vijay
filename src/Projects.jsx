const CATEGORIES = RAW_CATEGORIES.map(cat => ({
  ...cat,
  icon: CATEGORY_ICONS[cat.id] || CATEGORY_ICONS['ux-ui']
}))

export default function Projects({
  onBack,
  onOpenProject,
  activeCategory: parentActiveCategory,
  onCategoryChange
}) {
  const [internalCategory, setInternalCategory] = useState('ux-ui')
  const activeCategory = parentActiveCategory !== undefined ? parentActiveCategory : internalCategory
  const setActiveCategory = onCategoryChange || setInternalCategory
  const [selectedProject, setSelectedProject] = useState(null)

  const currentCategoryObj = CATEGORIES.find(c => c.id === activeCategory) || CATEGORIES[0]

  if (selectedProject) {
    const handleNext = () => {
      const idx = currentCategoryObj.projects.findIndex(p => p.id === selectedProject.id)
      const nextIdx = (idx + 1) % currentCategoryObj.projects.length
      setSelectedProject(currentCategoryObj.projects[nextIdx])
    }

    return (
      <ProjectDetail
        project={selectedProject}
        categoryLabel={currentCategoryObj.label}
        onBack={() => setSelectedProject(null)}
        onNavigateProject={handleNext}
      />
    )
  }

  const handleCardClick = (proj) => {
    if (onOpenProject) {
      onOpenProject(proj, currentCategoryObj.label, activeCategory)
    } else {
      setSelectedProject(proj)
    }
  }

  return (
    <div className="projects-container">
      {/* Background Image Layer */}
      <div className="projects-bg-image">
        <img src={bgImage} alt="" />
      </div>

      {/* Smooth Moving Purple Ball Layer */}
      <div className="page-ambient-glow-layer">
        <div className="page-moving-purple-orb" />
      </div>

      {/* Top Header Bar */}
      <header className="projects-topbar">
        <div className="projects-topbar-left">
          {onBack && (
            <button className="projects-home-btn" onClick={onBack} title="Back">
              <svg width="22" height="22" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.8" strokeLinecap="round" strokeLinejoin="round">
                <path d="M15 18l-6-6 6-6"/>
              </svg>
            </button>
          )}
        </div>
      </header>

      {/* Main Body: Sidebar + Grid */}
      <div className="projects-body">
        {/* Left Sidebar */}
        <aside className="projects-sidebar">
          {CATEGORIES.map((cat) => {
            const isActive = cat.id === activeCategory
            return (
              <div
                key={cat.id}
                className={`sidebar-item ${isActive ? 'active' : ''}`}
                onClick={() => setActiveCategory(cat.id)}
              >
                <div className="sidebar-item-icon">{cat.icon}</div>
                <span className="sidebar-item-label">{cat.label}</span>
              </div>
            )
          })}
        </aside>

        {/* Right Main Content Area */}
        <main className="projects-content-area">
          <div className="projects-category-heading">
            <span>{currentCategoryObj.label}</span>
            <span className="projects-count-badge">{currentCategoryObj.projects.length} Projects</span>
          </div>

          {/* 6 Projects Grid */}
          <div className="projects-grid">
            {currentCategoryObj.projects.map((proj) => (
              <div
                key={proj.id}
                className="project-card-wrapper"
                onClick={() => handleCardClick(proj)}
              >
                <div className={`project-grid-card ${proj.image ? 'with-image' : 'glass-card'}`}>
                  {proj.image ? (
                    <img src={proj.image} alt={proj.title} />
                  ) : (
                    <div className={`project-card-placeholder ${proj.theme || 'theme-dark'}`}>
                      {proj.icon && <span className="card-mock-icon">{proj.icon}</span>}
                      <span className="card-placeholder-text">{proj.tag || proj.title}</span>
                    </div>
                  )}
                </div>
                <div className="project-card-title">{proj.title}</div>
              </div>
            ))}
          </div>
        </main>
      </div>
    </div>
  )
}
